/* ---------------- Helpers shared by the scenes ---------------- */
/* Where a geographic point is, in PAGE coordinates (for the cursor and the real mouse) */
const pagePoint = (page, lat, lng) => page.evaluate(([la, ln]) => {
  const p = map.latLngToContainerPoint([la, ln]);
  const r = map.getContainer().getBoundingClientRect();
  return { x: r.left + p.x, y: r.top + p.y };
}, [lat, lng]);
/* The centre of a visible element found by its text (a RegExp: a string would match any case, as a substring) or by a selector */
async function centerOf(page, selector, text = null) {
  const loc = text ? page.locator(selector, { hasText: text }).first() : page.locator(selector).first();
  await loc.waitFor({ state: "visible", timeout: 20000 });
  const b = await loc.boundingBox();
  return { x: b.x + b.width / 2, y: b.y + b.height / 2 };
}
const MAIN_MENU = "#map-ctxmenu .ctx-menu-item";
const SUB_MENU = ".ctx-menu:not(#map-ctxmenu) .ctx-menu-item";
/* Choose «parent ▸ entry» in the context menu the way a person does: onto the parent, a click, then
   ALONG its row into the submenu and only then down to the entry. A diagonal slide would cross the
   next parent on the way and open ITS submenu (with the same entries) over the one wanted. */
async function pickSub(page, R, parent, entry) {
  const at = await centerOf(page, MAIN_MENU, parent);
  await R.glide(at, 4, 70, { hover: true });
  await R.click();
  const target = await centerOf(page, SUB_MENU, entry);
  await R.glide({ x: target.x, y: at.y }, 3, 60, { hover: true });
  await R.glide(target, 3, 60, { hover: true });
  await R.snap(400);
  await R.click();
}

/* ================= 1. Line of sight and Fresnel zone over real terrain ================= */
/* From Manzanares el Real (911 m) to a summit of the Cuerda Larga (2149 m), 9 km away and 1 238 m higher.
   With towers of 10 m a ridge a third of the way blocks the line of sight; a taller tower at the start
   clears it, and the Fresnel zone still touches the terrain. (Chosen by searching the IGN's MDT25 for
   pairs where exactly that happens: the story is true of this real terrain.) */
const START = { lat: 40.7270, lng: -3.8640 };
const END = { lat: 40.7990, lng: -3.9120 };

async function fresnel({ page, R, settle }) {
  await installCursor(page);
  await page.evaluate(([a, b]) => {
    setMeasureUnit("km"); setAltitudeUnit("m");
    const m = buildRouteMeasurement([a, b]);
    finalizeRouteMeasurement(m);
    /* the route in the upper part of the map: the profile window will cover the lower part */
    map.fitBounds(m.group.getBounds(), { animate: false, paddingTopLeft: [60, 40], paddingBottomRight: [60, 400] });
  }, [START, END]);
  await settle();
  await page.mouse.move(900, 60);
  await R.moveTo(900, 60); R.cur = { x: 900, y: 60 };
  await R.snap(1500);

  /* Right-click on the route → «Get profile» */
  const mid = await pagePoint(page, (START.lat + END.lat) / 2, (START.lng + END.lng) / 2);
  await R.glide(mid, 9, 70, { hover: true });
  await R.click({ button: "right" });
  const item = await centerOf(page, MAIN_MENU, /^Get profile$/);
  await R.glide(item, 5, 70, { hover: true });
  await R.snap(500);
  await R.click();
  /* The download is LIVE (a handful of requests to the IGN): the first frames show it going,
     then it is waited for without recording */
  await page.waitForSelector("#profile-dialog:not([hidden])");
  await R.snap(700);
  await page.waitForFunction(() => typeof profileChart !== "undefined" && !profileChart.hidden, null, { timeout: 180000 });
  await page.waitForTimeout(600);
  /* the window along the bottom, wide and not too tall, and the map left free */
  await page.evaluate(() => {
    const box = document.querySelector("#profile-dialog .dlg-box");
    box.style.width = "1100px"; box.style.height = "372px";
  });
  await page.evaluate(() => { const box = document.querySelector("#profile-dialog .dlg-box"); const r = box.getBoundingClientRect();
    box.style.left = `${Math.round((innerWidth - r.width) / 2)}px`; box.style.top = `${innerHeight - r.height - 12}px`; box.style.transform = "none"; });
  await page.waitForTimeout(500);
  await R.snap(1800);

  /* Towers of 10 m, then the start–end line and the Fresnel ellipsoid */
  const press = async sel => { const c = await centerOf(page, sel); await R.glide(c, 6, 60, { hover: true }); await R.click(); await R.snap(600); };
  const tower = async (sel, value) => {
    const c = await centerOf(page, sel);
    await R.glide(c, 5, 60, { hover: true });
    await page.mouse.click(c.x, c.y, { clickCount: 3 });
    await page.keyboard.type(value, { delay: 120 });
    await page.keyboard.press("Tab");
    await page.waitForTimeout(300);
    await R.snap(800);
  };
  /* where a distance (in metres along the route) is on the chart, in page coordinates */
  const chartAt = (metres, f = 0.45) => page.evaluate(([d, k]) => {
    const r = document.querySelector("#profile-chart svg").getBoundingClientRect();
    return { x: r.x + profileLayout.xOf(d), y: r.y + r.height * k };
  }, [metres, f]);
  await tower("#pf-tower-a", "10");
  await tower("#pf-tower-b", "10");
  await press("#pf-los");
  await press("#pf-fresnel");
  await R.snap(1200);

  /* Zoom in with the wheel on the ridge a third of the way (the heights rescale to what is shown) */
  const RIDGE = 3000;
  await R.glide(await chartAt(RIDGE), 7, 70, { hover: true });
  for (let i = 0; i < 4; i++) {
    await page.mouse.wheel(0, -240);
    await page.waitForTimeout(300);
    await R.snap(300);
  }
  await R.glide(await chartAt(RIDGE), 3, 70, { hover: true, wait: 150 });
  await R.snap(2400);                       /* blocked: the line cuts the ridge, and the readout gives the clearance */

  /* A taller tower at the start clears it, and the Fresnel zone still touches the ground */
  await tower("#pf-tower-a", "60");
  await R.glide(await chartAt(RIDGE), 3, 70, { hover: true, wait: 150 });
  await R.snap(2600);

  /* The whole route again, and hover along it: the red line follows, and so does the arrow on the map */
  await R.glide(await centerOf(page, "#pf-reset"), 7, 70, { hover: true });
  await R.click();
  await page.waitForTimeout(400);
  await R.glide(await chartAt(700), 6, 70, { hover: true });
  for (const m of [2200, 3700, 5200, 6700, 8100]) await R.glide(await chartAt(m), 5, 80, { hover: true, wait: 60 });
  await R.snap(2000);
}

/* ================= 2. A GeoTIFF as a map layer ================= */
/* The IGN's MDT25 over the Sierra de Guadarrama (© Instituto Geográfico Nacional de España, CC BY 4.0) */
const MDT25_URL = "https://servicios.idee.es/wcs-inspire/mdt?service=WCS&version=2.0.1&request=GetCoverage"
  + "&coverageId=Elevacion4258_25&format=GEOTIFFINT16&subset=Lat(40.70,40.90)&subset=Long(-4.15,-3.80)";

/* The WCS answers an uncompressed striped 16-bit GeoTIFF: read it and write it back as a tiled COG
   with overviews (what the application is built for) */
function stripsToCog(buf) {
  const ifd = buf.readUInt32LE(4), n = buf.readUInt16LE(ifd);
  const SZ = { 1: 1, 2: 1, 3: 2, 4: 4, 12: 8 }, tag = {};
  for (let i = 0; i < n; i++) {
    const p = ifd + 2 + 12 * i, t = buf.readUInt16LE(p), ty = buf.readUInt16LE(p + 2), c = buf.readUInt32LE(p + 4);
    const at = SZ[ty] * c <= 4 ? p + 8 : buf.readUInt32LE(p + 8);
    tag[t] = Array.from({ length: c }, (_, k) => ty === 3 ? buf.readUInt16LE(at + 2 * k) : ty === 4 ? buf.readUInt32LE(at + 4 * k)
      : ty === 12 ? buf.readDoubleLE(at + 8 * k) : buf[at + k]);
  }
  const w = tag[256][0], h = tag[257][0];
  if (tag[258][0] !== 16 || tag[259][0] !== 1 || !tag[273]) throw new Error("the WCS answer is not the uncompressed striped 16-bit TIFF this expects");
  const data = new Int16Array(w * h);
  let o = 0;
  tag[273].forEach((off, i) => { for (let k = 0; k < tag[279][i] / 2; k++) data[o++] = buf.readInt16LE(off + 2 * k); });
  const px = tag[33550][0], ox = tag[33922][3], oy = tag[33922][4];
  const NODATA = -9999;
  const level = (f, i) => ({ w: Math.ceil(w / f), h: Math.ceil(h / f), nodata: NODATA, subfile: i ? 1 : 0,
    dem: (x, y) => data[Math.min(h - 1, y * f) * w + Math.min(w - 1, x * f)],
    ...(i ? {} : { geo: { model: 2, epsg: 4326, ox, oy, px } }) });
  return writeTiff([1, 2, 4, 8].map(level));
}

async function geotiff({ page, R, settle }) {
  const r = await fetch(MDT25_URL, { headers: { "user-agent": UA } });
  if (!r.ok) throw new Error(`the IGN WCS answered ${r.status}`);
  const cog = stripsToCog(Buffer.from(await r.arrayBuffer()));
  await installCursor(page, { name: "MDT25_Guadarrama.tif", bytes: cog, type: "image/tiff", badge: "TIF" });

  await page.evaluate(() => { setAltitudeUnit("m"); setMeasureUnit("km"); map.setView([40.80, -3.975], 10, { animate: false }); });
  await settle();
  await R.snap(1500);

  /* The file is dragged onto the panel and dropped */
  const dropBox = await R.center("#dropzone");
  R.cur = { x: 960, y: 80 };
  await R.moveTo(R.cur.x, R.cur.y);
  await page.evaluate(() => window.__demo.chip(true));
  await R.snap(500);
  await R.glide({ x: 640, y: 220 }, 6, 70);
  await page.evaluate(([x, y]) => window.__demo.fire("dragover", x, y), [R.cur.x, R.cur.y]);
  await R.glide({ x: dropBox.x, y: dropBox.y - 30 }, 10, 70, { drag: true });
  await R.glide({ x: dropBox.x, y: dropBox.y }, 3, 90, { drag: true });
  await R.snap(800);
  await page.evaluate(([x, y]) => window.__demo.fire("drop", x, y), [R.cur.x, R.cur.y]);
  await page.evaluate(() => window.__demo.chip(false));
  await page.waitForFunction(() => [...document.querySelectorAll("#tree li")].some(l => l._name && /MDT25/.test(l._name)), null, { timeout: 60000 });
  await page.waitForTimeout(1800);
  await settle();
  await R.snap(1800);

  /* Frame it, and sweep the cursor from the valley to the summit: the altitude under it is read from the file */
  await page.evaluate(() => map.fitBounds([[40.70, -4.15], [40.90, -3.80]], { animate: false, padding: [24, 24] }));
  await page.waitForTimeout(1500);
  await settle();
  const path = [[40.73, -4.00], [40.77, -3.995], [40.80, -3.985], [40.83, -3.965], [40.85, -3.9547]];
  const pts = [];
  for (const [la, ln] of path) pts.push(await pagePoint(page, la, ln));
  await R.glide(pts[0], 6, 70, { hover: true, wait: 250 });
  for (const p of pts.slice(1)) await R.glide(p, 7, 90, { hover: true, wait: 250 });
  await R.snap(2200);
}

/* ================= 3. Wikipedia articles and an itinerary ================= */
/* A stand-in for the openrouteservice answer (the documented GeoJSON format): a walk from the
   Puerta del Sol to Cibeles along the Calle de Alcalá. Used ONLY when there is no ORS_API_KEY. */
const ORS_STAND_IN = { type: "FeatureCollection", features: [{ type: "Feature",
  properties: { summary: { distance: 1124.6, duration: 809.7 }, way_points: [0, 6] },
  geometry: { type: "LineString", coordinates: [[-3.70379, 40.416775], [-3.70275, 40.41705], [-3.7019, 40.4175], [-3.6995, 40.4183],
    [-3.6968, 40.4189], [-3.6948, 40.41905], [-3.6931, 40.4192]] } }] };
const CIBELES = { lat: 40.4192, lng: -3.6931 };

async function wikipedia({ page, R, settle }) {
  await installCursor(page);
  if (!ORS_KEY) {
    await page.route(/api\.openrouteservice\.org/, route => route.fulfill({ status: 200, contentType: "application/json",
      body: JSON.stringify(ORS_STAND_IN), headers: { "access-control-allow-origin": "*" } }));
  }
  /* the application only offers itineraries with a key in Properties: put one in directly */
  await page.evaluate(k => { orsKey = k; }, ORS_KEY || "demo-key-not-sent-anywhere");
  /* the view with Sol and Cibeles in the lower half of the map: «Calculate itinerary» opens over the upper half */
  await page.evaluate(() => { setMeasureUnit("km"); setAltitudeUnit("m"); map.setView([40.4180, -3.6985], 16, { animate: false }); map.panBy([0, -170], { animate: false }); });
  await settle();
  await page.mouse.move(900, 60);
  await R.moveTo(900, 60); R.cur = { x: 900, y: 60 };
  await R.snap(1300);

  /* Right-click on the map → Queries → Wikipedia articles in the view */
  const centre = await pagePoint(page, 40.4180, -3.6985);
  await R.glide(centre, 6, 70, { hover: true });
  await R.click({ button: "right" });
  await pickSub(page, R, /^Queries/, /^Wikipedia articles/);
  await page.waitForFunction(() => [...document.querySelectorAll("#tree li")].filter(li => li._mstyle && li._mstyle.icon === "wikipedia").length >= 20,
    null, { timeout: 60000 });
  await page.waitForTimeout(1200);
  await settle();
  await R.snap(2000);

  /* Rest on an article: its card has the summary and the link */
  const sol = await page.evaluate(() => {
    const li = [...document.querySelectorAll("#tree li")].find(x => x._name === "Puerta del Sol");
    if (!li) return null;
    const p = soleMarker(li).getLatLng(); return { lat: p.lat, lng: p.lng };
  });
  if (!sol) throw new Error("«Puerta del Sol» is not among the articles the live Wikipedia returned");
  const solAt = await pagePoint(page, sol.lat, sol.lng);
  await R.glide(solAt, 6, 70, { hover: true });
  await page.waitForSelector("#desc-dialog:not([hidden])", { timeout: 15000 });
  await page.waitForTimeout(500);
  await R.snap(2600);

  /* Right-click on that article → Itinerary from → that article (there are overlapping markers in the
     centre of Madrid, so the menu has one entry per layer under the pointer: the one whose card is open) */
  const title = (await page.locator("#desc-title").first().textContent()).trim();
  const exact = t => new RegExp(`^${t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}$`);
  await R.click({ button: "right" });
  await pickSub(page, R, /^Itinerary from ▸/, exact(title));
  await page.waitForTimeout(400);

  /* In «Calculate itinerary»: «Pick on the map» for the destination, and click on the map where it goes
     (a spot with no marker on it: it would be taken as that marker) */
  await R.glide(await centerOf(page, "#route-to-pick"), 6, 70, { hover: true });
  await R.snap(400);
  await R.click();
  await page.waitForTimeout(500);
  await R.snap(500);
  const base = await pagePoint(page, CIBELES.lat, CIBELES.lng);
  const free = await page.evaluate(({ x, y }) => {
    for (const [dx, dy] of [[0, 0], [30, 0], [-30, 0], [0, 30], [0, -30], [30, 30], [-30, -30], [45, 0], [0, 45]]) {
      const el = document.elementFromPoint(x + dx, y + dy);
      if (el && el.closest("#map") && !el.closest(".leaflet-marker-icon, .leaflet-control, .leaflet-popup, .dlg-float")) return { x: x + dx, y: y + dy };
    }
    return { x, y };
  }, base);
  await R.glide(free, 7, 70, { hover: true });
  await R.snap(400);
  await R.click();
  await page.waitForSelector("#route-calc", { state: "visible", timeout: 15000 });
  await page.waitForFunction(() => document.getElementById("route-to").value.trim() !== "", null, { timeout: 15000 });
  await page.selectOption("#route-profile", "foot-walking");
  await page.waitForTimeout(300);
  await R.snap(1500);

  /* Calculate */
  await R.glide(await centerOf(page, "#route-calc"), 6, 70, { hover: true });
  await R.snap(400);
  await R.click();
  await page.waitForFunction(() => [...document.querySelectorAll("#tree li")].some(li => /^Itinerary 1/.test(li._name || "")), null, { timeout: 60000 });
  await page.waitForTimeout(900);
  await settle();
  await page.mouse.move(900, 80);
  await R.glide({ x: 900, y: 80 }, 3, 80, { hover: true });
  /* Close the window: the whole itinerary, and its row in the tree */
  await R.glide(await centerOf(page, "#route-dialog .dlg-close"), 7, 70, { hover: true });
  await R.click();
  await page.waitForTimeout(500);
  await R.glide({ x: 760, y: 120 }, 6, 70, { hover: true });
  await R.snap(3200);
}

/* ================= The runner ================= */
const SCENES = {
  fresnel: { run: fresnel, viewport: { width: 1180, height: 760 } },
  geotiff: { run: geotiff, viewport: { width: 1100, height: 700 } },
  wikipedia: { run: wikipedia, viewport: { width: 1100, height: 700 } }
};
const names = wanted.length ? wanted : Object.keys(SCENES);
for (const n of names) if (!SCENES[n]) { console.error(`unknown scene «${n}» (${Object.keys(SCENES).join(", ")})`); process.exit(1); }

for (const name of names) {
  console.log(`── ${name}`);
  const { page, settle, close } = await openDemoApp({ viewport: SCENES[name].viewport, tool: "demo-scenes", noBg: NO_BG });
  try {
    const R = recorder(page, { stamp: STAMP });
    await SCENES[name].run({ page, R, settle });
    console.log(`   ${R.frames.length} frames`);
    const dir = DUMP && path.join(DUMP, name);
    if (dir) {
      dumpFrames(R.frames, dir);
      /* the long pauses are the moments the clip is about: the ones to review */
      console.log("   holds:", R.frames.map((f, i) => [i, f.delay]).filter(([, d]) => d >= 1200).map(([i, d]) => `f${i}(${d})`).join(" "));
    }
    encodeGif(R.frames, path.join(ROOT, "media", `kite-${name}.gif`), { picks: [0, 0.2, 0.4, 0.6, 0.8, 1], dump: dir });
  } catch (e) {
    /* a step looked for a menu entry that is not there: say what the menus do offer */
    const menus = await page.evaluate(() => [...document.querySelectorAll(".ctx-menu")].filter(m => !m.hidden && m.offsetParent !== null)
      .map(m => (m.id || "submenu") + ": " + [...m.querySelectorAll(".ctx-menu-item")].map(i => i.textContent.trim()).join(" | "))).catch(() => []);
    if (menus.length) console.error("   menus open when it failed:\n     " + menus.join("\n     "));
    if (DUMP) { fs.mkdirSync(DUMP, { recursive: true }); await page.screenshot({ path: path.join(DUMP, `${name}-failure.png`) }).catch(() => {}); }
    throw e;
  } finally {
    await close();
  }
}
