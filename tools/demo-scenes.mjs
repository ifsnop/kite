/* The showcase animations of the README (media/kite-fresnel.gif, media/kite-geotiff.gif and
   media/kite-wikipedia.gif): three of the best things KITE Local does, each in a short clip.
   Generated by a script, like the cover GIF (tools/demo-gif.mjs) and the screenshots of the
   manual, so that when the interface changes they are regenerated with one command and never
   show an application that no longer exists.

   Use:
     npm run demo-scenes                       all three
     npm run demo-scenes -- fresnel geotiff    only those
     npm run demo-scenes -- --sin-fondo        without OpenStreetMap tiles (flat tiles) to iterate the script
     npm run demo-scenes -- --fotogramas dir   also every frame as a PNG (to review the script)
     ORS_API_KEY=… npm run demo-scenes -- wikipedia   the itinerary from the real openrouteservice

   WHAT IS REAL. The clips use real data, because a demo with invented terrain would be a lie
   about what the tool does:
   - fresnel:   the route profile is downloaded LIVE from the IGN's WCS services (MDT05 terrain,
                MDS surface), exactly as a user's click would;
   - geotiff:   an elevation model of the Sierra de Guadarrama is downloaded from the IGN's WCS
                (MDT25) when the script runs and rebuilt as a proper tiled COG with overviews,
                so that the application's own warning about non-COG files does not show;
   - wikipedia: the articles are asked LIVE from en.wikipedia.org. The itinerary is the one thing
                that cannot be real without a key: with no `ORS_API_KEY` the script answers the
                openrouteservice request with a STAND-IN (the same documented shape the tests
                use), and the README caption says so; with a key it asks the real service (the
                key goes to that server only, and is never printed or written).
   The result therefore changes a little with each run (the services are live).

   The clips are in English, which is the language of the README.                          */
